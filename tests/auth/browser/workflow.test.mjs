import test, { before, after } from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync } from "node:fs";
import puppeteer from "puppeteer-core";
import { startFixture, details } from "../support/fixture.mjs";
let f, base, browser;
before(async () => { f = await startFixture(); base = f.base; });
after(async () => { await browser?.close(); await f?.stop(); });
test("browser completes register -> sign-in -> member access -> signout without storing secrets", { timeout: 60000 }, async () => {
  const chrome = process.env.CHROME_PATH || "C:/Program Files/Google/Chrome/Application/chrome.exe";
  assert.ok(existsSync(chrome), "Set CHROME_PATH to the installed Chrome executable");
  browser = await puppeteer.launch({ executablePath: chrome, headless: true });
  const context = await browser.createBrowserContext(); const page = await context.newPage();
  await page.setViewport({ width: 1440, height: 1000 });
  await page.setRequestInterception(true);
  page.on("request", (r) => r.url().startsWith(base) || /fonts\.googleapis\.com|fonts\.gstatic\.com/.test(r.url()) ? r.continue() : r.abort());
  const errors = []; page.on("pageerror", (e) => errors.push(e.message));
  const ready = () => page.waitForFunction(() => !document.querySelector('button[type="submit"]')?.disabled);
  const fill = async (selector, value) => { await page.$eval(selector, (el) => { el.focus(); el.select(); }); await page.type(selector, value); };
  await page.goto(base + "/sign-in?mode=signup&next=%2Fstudio", { waitUntil: "networkidle0" }); await ready();
  await page.evaluate(() => localStorage.setItem("buildgen_auth_user", JSON.stringify({ id: "forged", name: "Mustafa", password: "admin" })));
  await page.reload({ waitUntil: "networkidle0" }); await ready();
  assert.equal(await page.evaluate(() => localStorage.getItem("buildgen_auth_user")), null);
  await fill("#fullName", "Browser O'Connor"); await fill("#email", "browser@example.com");
  await fill("#password", details("").password); await fill("#confirmPassword", details("").password);
  mkdirSync("tests/artifacts/auth", { recursive: true });
  await page.screenshot({ path: "tests/artifacts/auth/signup.png", fullPage: true });
  await page.click('button[type="submit"]');
  await page.waitForFunction(() => new URL(location.href).searchParams.get("registered") === "1"); await ready();
  assert.equal(await page.$("#confirmPassword"), null);
  assert.equal((await context.cookies()).filter((c) => c.name.startsWith("buildgen_")).length, 0);
  await fill("#password", "wrong-password-123"); await page.click('button[type="submit"]');
  await page.waitForSelector('[role="alert"]'); assert.match(page.url(), /sign-in/); await ready();
  await fill("#password", details("").password);
  const loginResponse = page.waitForResponse((r) => r.url().endsWith("/api/auth/login") && r.request().method() === "POST");
  await page.click('button[type="submit"]');
  const login = await loginResponse;
  assert.equal(login.status(), 200);
  await page.waitForFunction(() => location.pathname === "/studio");
  assert.equal(new URL(page.url()).pathname, "/studio");
  assert.ok((await context.cookies()).filter((c) => c.name.startsWith("buildgen_")).every((c) => c.httpOnly && c.secure));
  assert.deepEqual(await page.evaluate(() => Object.keys(localStorage)), []);
  await page.goto(base + "/sign-in", { waitUntil: "networkidle0" });
  await page.waitForFunction(() => [...document.querySelectorAll("button")].some((b) => b.textContent === "Sign out" && !b.disabled));
  await page.screenshot({ path: "tests/artifacts/auth/signin-authenticated.png", fullPage: true });
  await Promise.all([page.waitForNavigation({ waitUntil: "networkidle0" }), page.evaluate(() => [...document.querySelectorAll("button")].find((b) => b.textContent === "Sign out").click())]);
  await page.goto(base + "/studio", { waitUntil: "networkidle0" }); assert.equal(new URL(page.url()).pathname, "/sign-in");
  await page.setViewport({ width: 390, height: 844 }); await page.goto(base + "/sign-in?mode=signup", { waitUntil: "networkidle0" }); await ready();
  await page.screenshot({ path: "tests/artifacts/auth/mobile-signup.png", fullPage: true });
  assert.deepEqual(errors, []);
  await context.close();
});
